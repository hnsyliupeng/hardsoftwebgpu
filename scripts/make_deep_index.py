#!/usr/bin/env python3
"""Build docs/DEEP_FUSION_INDEX.md from the committed R6-R10 gallery records.

Reads examples/structure_gallery_<round>_open_<res>/deep_*/design.json and gallery.json.
Every number in the index comes from those files; nothing is typed by hand.
Run from the repository root:  python3 scripts/make_deep_index.py
"""
import glob
import json
import os

ROUNDS = [
    ("R6", "r6", "sheet-to-strut morph", "gyroid core morphs radially into a BCC strut shell"),
    ("R7", "r7", "graded period", "gyroid period graded 3 to 7 mm along z"),
    ("R8", "r8", "radius from field", "BCC strut radius set by a gyroid field"),
    ("R9", "r9", "gated interpenetration (cut)", "Schwarz D sheet and BCC lattice cut by a gyroid gate"),
    ("R10", "r10", "gated dominance (no cut)", "Schwarz D sheet and BCC lattice both present; gate sets thickness"),
    ("R11", "r11", "gate-set iso-level", "one gyroid whose iso-level is set by a gate field"),
    ("R12", "r12", "one-sided gate-set iso-level", "one gyroid whose iso-level runs from 0 to 0.35 across a gate field"),
]
RES = ["96", "192", "256"]


def load(rnd, res):
    base = f"examples/structure_gallery_{rnd}_open_{res}"
    dirs = sorted(glob.glob(f"{base}/deep_*"))
    if not dirs:
        return None
    d = dirs[0]
    design = json.load(open(os.path.join(d, "design.json")))
    v = design["validation"]
    m = v["metrics"]
    gal = json.load(open(os.path.join(base, "gallery.json")))
    gal = gal[0] if isinstance(gal, list) else gal
    failed = [c["name"] for c in gal["checks"] if not c["pass"]]
    return {
        "folder": os.path.relpath(d),
        "pass": bool(v["pass"]),
        "volume": m["volume_mm3"],
        "wall_p5": m["min_wall_p5_mm"],
        "components": m["components"],
        "triangles": m["triangles"],
        "genus": m["genus_handles"],
        "cavities": m["cavities"],
        "failed": failed,
    }


def main():
    lines = [
        "# Deep fusion index: R6 to R10, all resolutions",
        "",
        "Generated by `scripts/make_deep_index.py` from the committed records; do not edit by hand.",
        "Each row is one design at one resolution. Status is the gallery pass flag. A FAIL row is kept",
        "as a record and is not accepted as printable.",
        "",
        "Shared settings: 20 mm box, open designs (`skin_mm = 0`), field-based (non-exact) geometry,",
        "dual contouring, one connected solid, watertight mesh. Wall = 5th percentile of inward ray chords",
        "(validator rule for coupled designs); floor 0.4 mm.",
        "",
        "| Round | Dimension | Cells | Status | Volume (mm³) | Wall p5 (mm) | Components | Genus | Cavities | Triangles | Failed checks | Folder |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    status_counts = {"PASS": 0, "FAIL": 0}
    for rid, rnd, dim, _ in ROUNDS:
        for res in RES:
            r = load(rnd, res)
            if r is None:
                lines.append(f"| {rid} | {dim} | {res} | missing | | | | | | | | |")
                continue
            st = "PASS" if r["pass"] else "FAIL"
            status_counts[st] += 1
            failed = ", ".join(r["failed"]) if r["failed"] else "none"
            lines.append(
                f"| {rid} | {dim} | {res} | {st} | {r['volume']:.1f} | {r['wall_p5']:.3f} | "
                f"{r['components']} | {r['genus']} | {r['cavities']} | {r['triangles']:,} | {failed} | `{r['folder']}` |"
            )
    lines += [
        "",
        f"Totals: {status_counts['PASS']} PASS, {status_counts['FAIL']} FAIL out of {sum(status_counts.values())} records.",
        "",
        "## Round descriptions",
        "",
    ]
    for rid, rnd, dim, desc in ROUNDS:
        lines.append(f"- **{rid} ({dim})**: {desc}.")
    lines += [
        "",
        "## Limits",
        "",
        "- Wall p5 is a chord statistic. It is not a certified manufacturing check.",
        "- Slice tests (`scripts/slice_test.ts`) were run on R10 at 96 cells only; they confirm open faces (face solid fraction 0.49 to 0.51).",
        "  The field does not depend on mesh resolution, so the same values apply at 192 and 256 at the field level.",
        "- R9 at 256 fails the 0.4 mm wall floor. Its thin walls are acute wedges at the gate cut (see `docs/DEEP_FUSION_ROUNDS.md`).",
        "  The 0.6 mm blend and the morphological opening trials did not fix it and are recorded as rejected.",
        "- R11 void channels were checked with `scripts/r11_void_check.ts` (complement chord routine, 96 cells): void p5 2.06 mm, minimum 1.46 mm.",
        "- R10 and R11 redistribute material between gate zones but leave the whole-box solid fraction unchanged (symmetric gate); see the coupling analyses in `docs/`.",
        "- Exact B-Rep and STEP are not available for any of these designs.",
        "",
    ]
    out = "docs/DEEP_FUSION_INDEX.md"
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {status_counts}")


if __name__ == "__main__":
    main()
