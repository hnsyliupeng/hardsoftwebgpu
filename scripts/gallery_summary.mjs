// Writes a summary table of a structure gallery from its gallery.json (no re-computation).
// Usage: node scripts/gallery_summary.mjs <gallery_dir>   -> writes <gallery_dir>/SUMMARY.md
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/gallery_summary.mjs <gallery_dir>");
const entries = JSON.parse(readFileSync(join(dir, "gallery.json"), "utf8"));

const rows = entries.map((e) => {
  const m = e.metrics ?? {};
  const pass = e.pass ? "PASS" : "FAIL";
  return `| \`${e.id}\` | ${e.title} | ${e.group} | ${pass} | ${m.components ?? "-"} | ${(m.volume_mm3 ?? NaN).toFixed(3)} | ${m.min_wall_p5_mm ?? "-"} | ${m.genus_handles ?? "-"} | ${(e.repair_history ?? []).length} |`;
});

const md = [
  "# Gallery summary (generated from gallery.json)",
  "",
  "Generated by `scripts/gallery_summary.mjs`. Values are copied from `gallery.json`; nothing is recomputed here.",
  "Volumes are field-based (surface nets of the SDF), not exact B-Rep, unless the README of the folder says otherwise.",
  "",
  "| id | title | group | check | components | volume (mm³) | min wall p5 (mm) | genus (handles) | repairs |",
  "|---|---|---|---|---|---|---|---|---|",
  ...rows,
  "",
].join("\n");

writeFileSync(join(dir, "SUMMARY.md"), md);
console.log(`wrote ${join(dir, "SUMMARY.md")} (${entries.length} entries)`);
