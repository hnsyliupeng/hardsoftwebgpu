// Writes web/compute/sc_field_wgsl.ts from scShaderSource() (src/topology/instanced.ts).
//   node --experimental-strip-types --no-warnings scripts/gen_sc_shader.ts
import { writeFileSync } from "node:fs";
import { scShaderSource } from "../src/topology/instanced.ts";

const src = scShaderSource();
if (src.includes("`") || src.includes("${")) throw new Error("shader text must not contain backticks or ${");
const out = `// Generated by scripts/gen_sc_shader.ts from src/topology/instanced.ts. Do not edit by hand.\nexport const SC_FIELD_WGSL = \`${src}\`;\n`;
writeFileSync("web/compute/sc_field_wgsl.ts", out);
console.log("wrote web/compute/sc_field_wgsl.ts", out.length, "bytes");
