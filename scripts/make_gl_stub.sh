#!/usr/bin/env bash
# Hosts without libGL: OCP (cadquery-ocp) loads libTKOpenGl, which needs libGL.so.1 at load time.
# B-Rep modelling and STEP I/O never call GL, so we provide a stub library that defines the GL
# symbols the bundled OCP libraries reference. Nothing is downloaded; the stub is built with gcc.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SITE="$(ls -d "$ROOT"/.venv/lib/python3*/site-packages)"
OUT="$ROOT/.venv/stubs"
mkdir -p "$OUT"
for f in "$SITE"/cadquery_ocp.libs/*.so* "$SITE"/OCP/*.so; do
  nm -D --undefined-only "$f" 2>/dev/null || true
done | awk '{print $2}' | grep -E '^(gl|GL|egl|EGL)' | sort -u > "$OUT/glsyms.txt"
{
  echo '/* generated by scripts/make_gl_stub.sh: no-op GL symbols for load-time linking only */'
  while read -r s; do echo "void $s(void){}"; done < "$OUT/glsyms.txt"
} > "$OUT/stub.c"
gcc -shared -fPIC -o "$OUT/libGL.so.1" -Wl,-soname,libGL.so.1 "$OUT/stub.c"
echo "stub: $OUT/libGL.so.1 ($(wc -l < "$OUT/glsyms.txt") symbols)"
